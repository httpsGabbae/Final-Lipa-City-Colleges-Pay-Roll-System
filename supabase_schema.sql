-- ------------------------------------------------------------
-- 0. Helper replacing MySQL's ON UPDATE CURRENT_TIMESTAMP
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

