-- ============================================================
-- LCC PAYROLL SYSTEM — PostgreSQL / Supabase schema
-- Converted from MySQL: schema.sql + attendance_portal.sql
--   + employee_portal.sql (all three folded into this one file)
--
-- SAFE FOR AN EXISTING DATABASE: no DROP TABLE anywhere.
-- Everything is IF NOT EXISTS / ON CONFLICT, so you can
-- run it and re-run it safely in Supabase SQL Editor.
--
-- How to use:
--   1. Supabase Dashboard > SQL Editor > New query.
--   2. Paste this whole file > Run.
--
-- MySQL -> PostgreSQL mapping used:
--   INT AUTO_INCREMENT       -> INTEGER GENERATED BY DEFAULT AS IDENTITY
--   ENUM(...)                -> VARCHAR + CHECK (...) (no custom types needed)
--   TIMESTAMP ON UPDATE ...  -> TIMESTAMPTZ + updated_at trigger (see bottom)
--   ENGINE/CHARSET/COLLATE   -> removed (not applicable in Postgres)
--   ON DUPLICATE KEY UPDATE  -> ON CONFLICT ...
--   ALTER TABLE ... AUTO_INCREMENT = N -> setval(...) sequence reset (bottom)
-- ============================================================

-- ------------------------------------------------------------
-- 0. Helper replacing MySQL's ON UPDATE CURRENT_TIMESTAMP
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

