CREATE TABLE IF NOT EXISTS public.employees (
    employee_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_no VARCHAR(20) NOT NULL UNIQUE,
    portal_password VARCHAR(255),
    photo_path VARCHAR(255),

    first_name VARCHAR(50) NOT NULL,
    middle_name VARCHAR(50),
    last_name VARCHAR(50) NOT NULL,

    gender VARCHAR(10) NOT NULL DEFAULT 'Other'
        CHECK (gender IN ('Male', 'Female', 'Other')),
    birth_date DATE,
    contact_number VARCHAR(20),
    email VARCHAR(100),
    civil_status VARCHAR(30),
    nationality VARCHAR(50),
    religion VARCHAR(50),

    permanent_address TEXT,
    present_address TEXT,

    sss_no VARCHAR(30),
    philhealth_no VARCHAR(30),
    pagibig_no VARCHAR(30),
    tin_no VARCHAR(30),
    atm_no VARCHAR(40),

    department VARCHAR(150),
    position VARCHAR(120),
    employment_status VARCHAR(20) NOT NULL DEFAULT 'Regular'
        CHECK (employment_status IN ('Regular', 'Probationary', 'Contractual', 'Part-Time')),

    basic_salary NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    date_hired DATE,

    emergency_contact_name VARCHAR(100),
    emergency_contact_phone VARCHAR(30),
    emergency_contact_address TEXT,

    dependent_name VARCHAR(100),
    dependent_relationship VARCHAR(50),
    dependent_birth_date DATE,

    education_background TEXT,
    character_reference TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_employee_department ON public.employees (department);
CREATE INDEX IF NOT EXISTS idx_employee_status ON public.employees (employment_status);
