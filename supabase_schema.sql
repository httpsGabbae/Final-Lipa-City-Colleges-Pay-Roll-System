-- ------------------------------------------------------------
-- 6. ATTENDANCE
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.attendance (
    attendance_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL,
    attendance_date DATE NOT NULL,
    time_in TIME,
    time_out TIME,
    status VARCHAR(10) NOT NULL DEFAULT 'Present'
        CHECK (status IN ('Present', 'Late', 'Absent', 'On Leave', 'Half Day')),
    remarks VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_employee_attendance_date UNIQUE (employee_id, attendance_date),
    CONSTRAINT fk_attendance_employee
        FOREIGN KEY (employee_id)
        REFERENCES public.employees (employee_id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_attendance_date ON public.attendance (attendance_date);
CREATE INDEX IF NOT EXISTS idx_attendance_status ON public.attendance (status);

-- ------------------------------------------------------------
-- 7. EMPLOYEE REFERENCES
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.employee_references (
    reference_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL,
    reference_name VARCHAR(120) NOT NULL,
    reference_address TEXT,
    reference_occupation VARCHAR(100),
    reference_contact_number VARCHAR(40),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_reference_employee
        FOREIGN KEY (employee_id)
        REFERENCES public.employees (employee_id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_reference_employee ON public.employee_references (employee_id);

-- ------------------------------------------------------------
-- 8. PAYROLL RECORDS
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.payroll_records (
    payroll_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL,

    period_start DATE NOT NULL,
    period_end DATE NOT NULL,

    basic_salary NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    allowances NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    other_earnings NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    deductions NUMERIC(12,2) NOT NULL DEFAULT 0.00,

    gross_pay NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    net_pay NUMERIC(12,2) NOT NULL DEFAULT 0.00,

    status VARCHAR(10) NOT NULL DEFAULT 'Draft'
        CHECK (status IN ('Draft', 'Approved', 'Paid')),
    notes TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_payroll_employee
        FOREIGN KEY (employee_id)
        REFERENCES public.employees (employee_id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_payroll_employee ON public.payroll_records (employee_id);
CREATE INDEX IF NOT EXISTS idx_payroll_period ON public.payroll_records (period_start, period_end);
CREATE INDEX IF NOT EXISTS idx_payroll_status ON public.payroll_records (status);

