-- ------------------------------------------------------------
-- 8. PAYROLL RECORDS
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.payroll_records (
    payroll_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL,

    period_start DATE NOT NULL,
    period_end DATE NOT NULL,

    basic_salary NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    allowances NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    other_earnings NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    deductions NUMERIC(12,2) NOT NULL DEFAULT 0.00,

    gross_pay NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    net_pay NUMERIC(12,2) NOT NULL DEFAULT 0.00,

    status VARCHAR(10) NOT NULL DEFAULT 'Draft'
        CHECK (status IN ('Draft', 'Approved', 'Paid')),
    notes TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_payroll_employee
        FOREIGN KEY (employee_id)
        REFERENCES public.employees (employee_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_payroll_employee ON public.payroll_records (employee_id);
CREATE INDEX IF NOT EXISTS idx_payroll_period ON public.payroll_records (period_start, period_end);
CREATE INDEX IF NOT EXISTS idx_payroll_status ON public.payroll_records (status);

-- ------------------------------------------------------------
-- 9. updated_at auto-update triggers
-- (replaces MySQL ON UPDATE CURRENT_TIMESTAMP)
-- ------------------------------------------------------------
DROP TRIGGER IF EXISTS trg_departments_updated_at ON public.departments;
CREATE TRIGGER trg_departments_updated_at
    BEFORE UPDATE ON public.departments
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS trg_employees_updated_at ON public.employees;
CREATE TRIGGER trg_employees_updated_at
    BEFORE UPDATE ON public.employees
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS trg_attendance_updated_at ON public.attendance;
CREATE TRIGGER trg_attendance_updated_at
    BEFORE UPDATE ON public.attendance
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS trg_employee_references_updated_at ON public.employee_references;
CREATE TRIGGER trg_employee_references_updated_at
    BEFORE UPDATE ON public.employee_references
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS trg_payroll_records_updated_at ON public.payroll_records;
CREATE TRIGGER trg_payroll_records_updated_at
    BEFORE UPDATE ON public.payroll_records
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

